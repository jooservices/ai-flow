"""Generate docs/v4/events.md: every domain event, its owner and aggregate, payload fields and listeners.

`AIFLOW_WRITE_EVENTS_DOC=1 uv run pytest tests/v4/test_events_doc.py` rewrites the file; the test fails when it is stale,
so a new event or listener cannot land without its row. The catalog admission already refuses an event without an owner."""
from __future__ import annotations

import dataclasses

from .catalog import CATALOG
from .registry import Registry
from . import wiring


def build_registry() -> Registry:
    """A registry with every feature's listeners; their bodies close over a context that is never used here."""
    registry = Registry()
    for register in wiring._feature_installers():
        register(None, registry)
    return registry


def render() -> str:
    registry = build_registry()
    lines = ["# Domain events and listeners", "",
             "Generated by `control/platform/events/docgen.py`; do not edit by hand. See "
             "[Control plane structure](event-architecture.md).", "",
             "| Event | Owner | Aggregate | Payload | Listeners |", "| --- | --- | --- | --- | --- |"]
    for event_type in sorted(CATALOG):
        cls = CATALOG[event_type]
        payload = ", ".join(f"`{item.name}`" for item in dataclasses.fields(cls))
        listeners = ", ".join(f"`{listener.name}` ({listener.delivery})"
                              for listener in registry.listeners_for(event_type)) or "none"
        lines.append(f"| `{event_type}` v{cls.version} | {cls.owner} | {cls.aggregate} (`{cls.aggregate_field}`) |"
                     f" {payload} | {listeners} |")
    return "\n".join(lines) + "\n"
