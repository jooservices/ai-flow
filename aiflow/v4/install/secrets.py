"""Control-plane secrets under /etc/aiflow/secrets/control (directory 0700, every file 0600).

Internal secrets (database and OpenObserve passwords, provisioning key, owner and reviewer tokens, console session
key) are generated by `aiflow4 install control` the first time and never regenerated: a value that exists is kept.
Owner-supplied values (Jira, GitHub) are entered with `aiflow4 secret set NAME`, which reads them with echo off
(or from a pipe with --stdin) so they never appear on the terminal, in the shell history or in process arguments.
Nothing here prints a value; messages name the key and the file only.
"""
from __future__ import annotations

import base64
import getpass
import os
import re
import secrets
import sys
from pathlib import Path
from typing import Callable, TextIO

APP_ENV = "aiflow4.env"  # env_file of control-api and control-loops (deploy/v4/control/compose.yaml)
POSTGRES_ENV = "postgres.env"
OPENOBSERVE_ENV = "openobserve.env"
GITHUB_ENV = "github.env"  # GH_TOKEN for gh and GHCR when the release or image is private
DB_USER, DB_NAME = "aiflow", "aiflow4"
O2_USER = "owner@aiflow4.local"

# Values the owner provides; each lands in one file. Generated secrets are not in this list.
OWNER_SECRETS: dict[str, tuple[str, str]] = {
    "JIRA_EMAIL": (APP_ENV, "Atlassian account e-mail for the API-token fallback (the UI OAuth connection is preferred)"),
    "JIRA_API_TOKEN": (APP_ENV, "Atlassian API token for the API-token fallback"),
    "GH_TOKEN": (GITHUB_ENV, "GitHub token with read access to jooservices/ai-flow releases and GHCR packages"),
}
_SAFE_VALUE = re.compile(r"[\x21-\x7e]+")  # printable ASCII without spaces: safe in a compose/systemd env file
_SECRET_KEY = re.compile(r"PASSWORD|TOKEN|SECRET|BASIC|JIRA_EMAIL")


def read_env(path: Path) -> dict[str, str]:
    out: dict[str, str] = {}
    if path.is_file():
        for line in path.read_text(encoding="utf-8").splitlines():
            if line and not line.startswith("#") and "=" in line:
                key, value = line.split("=", 1)
                out[key.strip()] = value
    return out


def ensure_dir(path: Path, mode: int = 0o700) -> None:
    path.mkdir(parents=True, exist_ok=True)
    os.chmod(path, mode)


def update_env(path: Path, *, keep: dict[str, str] | None = None, force: dict[str, str] | None = None,
               header: str = "", mode: int = 0o600) -> bool:
    """Add `keep` keys that are missing and set `force` keys; other lines stay. Written atomically, `mode` from the
    first byte; returns whether the content changed (an unchanged file is not rewritten)."""
    lines = path.read_text(encoding="utf-8").splitlines() if path.is_file() else ([f"# {header}"] if header else [])
    current = read_env(path)
    wanted = dict(force or {})
    for key, value in (keep or {}).items():
        if not current.get(key):
            wanted[key] = value
    out, seen = [], set()
    for line in lines:
        key = line.split("=", 1)[0].strip() if "=" in line and not line.startswith("#") else ""
        if key in wanted:
            if key in seen:
                continue
            line = f"{key}={wanted[key]}"
            seen.add(key)
        out.append(line)
    out += [f"{k}={v}" for k, v in wanted.items() if k not in seen]
    text = "\n".join(out) + "\n"
    if path.is_file() and path.read_text(encoding="utf-8") == text:
        os.chmod(path, mode)
        return False
    if mode == 0o600:
        ensure_dir(path.parent)
    else:
        path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(f".{path.name}.tmp")
    fd = os.open(tmp, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, mode)
    with os.fdopen(fd, "w", encoding="utf-8") as f:
        f.write(text)
    os.chmod(tmp, mode)
    os.replace(tmp, path)
    return True


def ensure_internal(secret_dir: Path, public_url: str, gatus_url: str) -> list[str]:
    """Create the internal secrets that are missing; returns the names of the files that changed."""
    ensure_dir(secret_dir)
    pg = read_env(secret_dir / POSTGRES_ENV).get("POSTGRES_PASSWORD") or secrets.token_urlsafe(32)
    o2 = read_env(secret_dir / OPENOBSERVE_ENV).get("ZO_ROOT_USER_PASSWORD") or secrets.token_urlsafe(24)
    changed = []
    if update_env(secret_dir / POSTGRES_ENV, header="registry database (aiflow4 install control; do not edit by hand)",
                  keep={"POSTGRES_USER": DB_USER, "POSTGRES_DB": DB_NAME, "POSTGRES_PASSWORD": pg}):
        changed.append(POSTGRES_ENV)
    if update_env(secret_dir / OPENOBSERVE_ENV, header="OpenObserve root user (aiflow4 install control)",
                  keep={"ZO_ROOT_USER_EMAIL": O2_USER, "ZO_ROOT_USER_PASSWORD": o2}):
        changed.append(OPENOBSERVE_ENV)
    # The app file is derived from the two above, so a kept database password keeps a working URL.
    pg = read_env(secret_dir / POSTGRES_ENV)["POSTGRES_PASSWORD"]
    o2_env = read_env(secret_dir / OPENOBSERVE_ENV)
    o2_basic = base64.b64encode(f"{o2_env['ZO_ROOT_USER_EMAIL']}:{o2_env['ZO_ROOT_USER_PASSWORD']}".encode()).decode()
    if update_env(secret_dir / APP_ENV, header="control-api and control-loops (aiflow4 install control, aiflow4 secret set)",
                  keep={"AIFLOW4_DATABASE_URL": f"postgresql://{DB_USER}:{pg}@aiflow4-postgres:5432/{DB_NAME}",
                        "AIFLOW4_REDIS_URL": "redis://aiflow4-redis:6379/0",
                        "AIFLOW4_JOIN_TOKEN": secrets.token_urlsafe(32),
                        "AIFLOW4_OWNER_TOKEN": secrets.token_urlsafe(32),
                        "AIFLOW4_REVIEWER_TOKEN": secrets.token_urlsafe(32),
                        "AIFLOW4_CONSOLE_SESSION_SECRET": secrets.token_urlsafe(48),
                        "O2_BASIC": o2_basic},
                  force={"AIFLOW4_PUBLIC_URL": public_url, "AIFLOW4_GATUS_URL": gatus_url}):
        changed.append(APP_ENV)
    for name in (POSTGRES_ENV, OPENOBSERVE_ENV, APP_ENV):
        os.chmod(secret_dir / name, 0o600)
    return changed


def secret_values(secret_dir: Path) -> list[str]:
    """The secret values in the secret files (not user names or URLs), for masking command output; the database
    URL is covered by its password."""
    values = []
    if secret_dir.is_dir():
        for path in secret_dir.glob("*.env"):
            values += [v for k, v in read_env(path).items() if _SECRET_KEY.search(k) and len(v) >= 6]
    return values


def redact(text: str, values: list[str]) -> str:
    for value in sorted(values, key=len, reverse=True):
        text = text.replace(value, "***")
    return text


def read_hidden(name: str, *, from_stdin: bool, stdin: TextIO | None = None,
                prompt: Callable[[str], str] = getpass.getpass) -> str:
    """The value of NAME: from a pipe, or typed twice with echo off. Never from argv or the environment."""
    if from_stdin:
        return (stdin or sys.stdin).readline().rstrip("\r\n")
    first = prompt(f"{name} (input hidden): ")
    if first != prompt(f"{name} again: "):
        raise ValueError("the two entries differ; nothing was saved")
    return first


def set_owner_secret(secret_dir: Path, name: str, value: str) -> Path:
    if name not in OWNER_SECRETS:
        raise ValueError(f"unknown secret {name}; choose one of {', '.join(OWNER_SECRETS)}")
    if not _SAFE_VALUE.fullmatch(value):
        raise ValueError(f"{name} is empty or has spaces or non-ASCII characters; nothing was saved")
    path = secret_dir / OWNER_SECRETS[name][0]
    update_env(path, force={name: value})
    return path


def owner_secret_status(secret_dir: Path) -> dict[str, bool]:
    return {name: bool(read_env(secret_dir / file).get(name)) for name, (file, _) in OWNER_SECRETS.items()}
